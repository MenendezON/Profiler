import { type FormEvent } from 'react'
import { Link, useNavigate, useParams } from 'react-router'
import { useMutation, useQuery, useQueryClient } from '@tanstack/react-query'
import { supabase } from '@/lib/supabase'
import { unwrap } from '@/lib/utils'
import { Constants, type Enums, type TablesInsert } from '@/lib/database.types'
import { EMPLOYMENT_TYPES, EXPERIENCE_LEVELS, INDUSTRIES, OPENING_STATUS } from '@/lib/constants'
import { Alert, Button, Card, Checkbox, Field, Input, PageHeader, Select, Spinner, Textarea } from '@/components/ui'
import { BackTo } from '../settings/LocationsPages'
import { OPENINGS_KEY } from './OpeningsListPage'

const DESCRIPTION_TEMPLATE = 'Job brief:\n\n\nResponsibilities:\n- \n\nSkills required:\n- \n'

function useFormOptions() {
  return useQuery({
    queryKey: ['opening-form-options'],
    queryFn: async () => {
      const [locations, departments, templates] = await Promise.all([
        supabase.from('locations').select('id, name').order('name').then(unwrap),
        supabase.from('departments').select('id, name').order('name').then(unwrap),
        supabase.from('screening_templates').select('id, name, questions(count)').order('name').then(unwrap),
      ])
      return { locations, departments, templates }
    },
  })
}

export function OpeningFormPage() {
  const { id } = useParams()
  const isEdit = !!id
  const navigate = useNavigate()
  const qc = useQueryClient()
  const options = useFormOptions()

  const existing = useQuery({
    queryKey: [...OPENINGS_KEY, 'one', id],
    enabled: isEdit,
    queryFn: async () => unwrap(await supabase.from('openings').select('*').eq('id', id!).single()),
  })

  const save = useMutation({
    mutationFn: async (values: TablesInsert<'openings'>) =>
      isEdit
        ? unwrap(await supabase.from('openings').update(values).eq('id', id!).select('id').single())
        : unwrap(await supabase.from('openings').insert(values).select('id').single()),
    onSuccess: (row) => {
      qc.invalidateQueries({ queryKey: OPENINGS_KEY })
      qc.invalidateQueries({ queryKey: ['opening-status-counts'] })
      qc.invalidateQueries({ queryKey: ['dashboard-stats'] })
      navigate(`/openings/${row.id}`)
    },
  })

  function onSubmit(e: FormEvent<HTMLFormElement>) {
    e.preventDefault()
    const f = new FormData(e.currentTarget)
    const s = (k: string) => String(f.get(k) ?? '').trim()
    const orNull = (k: string) => s(k) || null
    save.mutate({
      title: s('title'),
      code: s('code'), // blank → generated by the database (e.g. FABR-004)
      description: s('description'),
      department_id: orNull('department_id'),
      location_id: orNull('location_id'),
      remote: f.get('remote') === 'on',
      type: s('type'),
      experience: s('experience'),
      industry: s('industry'),
      template_id: orNull('template_id'),
      status: s('status') as Enums<'opening_status'>,
    })
  }

  if (options.isLoading || (isEdit && existing.isLoading)) return <Spinner />
  const o = existing.data
  const { locations = [], departments = [], templates = [] } = options.data ?? {}
  const loadError = options.error ?? existing.error

  return (
    <>
      <BackTo to={isEdit ? `/openings/${id}` : '/openings'} label={isEdit ? 'Opening' : 'Job openings'} />
      <PageHeader title={isEdit ? `Edit ${o?.title ?? 'opening'}` : 'New job opening'} />

      <form onSubmit={onSubmit} className="grid gap-6 lg:grid-cols-3">
        <div className="space-y-6 lg:col-span-2">
          {(save.error || loadError) && <Alert>{(save.error ?? loadError)!.message}</Alert>}

          <Card className="space-y-4 p-6">
            <h2 className="text-sm font-semibold">Position</h2>
            <div className="grid gap-4 sm:grid-cols-3">
              <div className="sm:col-span-2">
                <Field label="Job title" htmlFor="title">
                  <Input id="title" name="title" defaultValue={o?.title} placeholder="IT Officer" required />
                </Field>
              </div>
              <Field label="Job code" htmlFor="code" hint={isEdit ? undefined : 'Leave blank to generate one.'}>
                <Input id="code" name="code" defaultValue={o?.code} placeholder="Auto" className="font-mono" />
              </Field>
            </div>
            <Field label="Description" htmlFor="description">
              <Textarea id="description" name="description" rows={12} defaultValue={o?.description ?? DESCRIPTION_TEMPLATE} />
            </Field>
          </Card>

          <Card className="space-y-4 p-6">
            <h2 className="text-sm font-semibold">Details</h2>
            <div className="grid gap-4 sm:grid-cols-2">
              <Field label="Department" htmlFor="department_id">
                <Select id="department_id" name="department_id" defaultValue={o?.department_id ?? ''}>
                  <option value="">— None —</option>
                  {departments.map((d) => <option key={d.id} value={d.id}>{d.name}</option>)}
                </Select>
                {!departments.length && <EmptyHint to="/settings/departments/new" label="Add a department" />}
              </Field>
              <Field label="Location" htmlFor="location_id">
                <Select id="location_id" name="location_id" defaultValue={o?.location_id ?? ''}>
                  <option value="">— None —</option>
                  {locations.map((l) => <option key={l.id} value={l.id}>{l.name}</option>)}
                </Select>
                {!locations.length && <EmptyHint to="/settings/locations/new" label="Add a location" />}
              </Field>
              <Field label="Employment type" htmlFor="type">
                <Select id="type" name="type" defaultValue={o?.type ?? 'Full Time'} required>
                  {EMPLOYMENT_TYPES.map((t) => <option key={t}>{t}</option>)}
                </Select>
              </Field>
              <Field label="Experience level" htmlFor="experience">
                <Select id="experience" name="experience" defaultValue={o?.experience ?? ''} required>
                  <option value="" disabled>— Select —</option>
                  {withCurrent(EXPERIENCE_LEVELS, o?.experience).map((t) => <option key={t}>{t}</option>)}
                </Select>
              </Field>
              <Field label="Industry" htmlFor="industry">
                <Select id="industry" name="industry" defaultValue={o?.industry ?? ''} required>
                  <option value="" disabled>— Select —</option>
                  {withCurrent(INDUSTRIES, o?.industry).map((t) => <option key={t}>{t}</option>)}
                </Select>
              </Field>
              <div className="flex items-end pb-2">
                <Checkbox name="remote" defaultChecked={o?.remote ?? false} label="Remote work possible" />
              </div>
            </div>
          </Card>
        </div>

        <div className="space-y-6">
          <Card className="space-y-4 p-6">
            <h2 className="text-sm font-semibold">Visibility</h2>
            <fieldset className="space-y-2">
              <legend className="sr-only">Status</legend>
              {Constants.public.Enums.opening_status.map((s) => (
                <label key={s} className="flex cursor-pointer items-start gap-3 rounded-lg border border-slate-200 p-3 has-[:checked]:border-brand-500 has-[:checked]:bg-brand-50">
                  <input type="radio" name="status" value={s} defaultChecked={(o?.status ?? 'unpublished') === s} className="mt-0.5 accent-brand-600" />
                  <span>
                    <span className="block text-sm font-medium">{OPENING_STATUS[s].label}</span>
                    <span className="block text-xs text-slate-500">{OPENING_STATUS[s].hint}</span>
                  </span>
                </label>
              ))}
            </fieldset>
          </Card>

          <Card className="space-y-3 p-6">
            <h2 className="text-sm font-semibold">Application form</h2>
            <Field label="Screening questions" htmlFor="template_id" hint="Extra questions candidates answer when applying.">
              <Select id="template_id" name="template_id" defaultValue={o?.template_id ?? ''}>
                <option value="">— Standard form only —</option>
                {templates.map((t) => (
                  <option key={t.id} value={t.id}>{t.name} ({t.questions[0]?.count ?? 0} questions)</option>
                ))}
              </Select>
            </Field>
            <Link to="/settings/screening-templates" className="text-xs font-medium text-brand-600 hover:underline">Manage templates</Link>
          </Card>

          <div className="flex gap-2">
            <Link to={isEdit ? `/openings/${id}` : '/openings'} className="flex-1">
              <Button type="button" variant="secondary" className="w-full">Cancel</Button>
            </Link>
            <Button type="submit" loading={save.isPending} className="flex-1">{isEdit ? 'Save changes' : 'Create opening'}</Button>
          </div>
        </div>
      </form>
    </>
  )
}

/** Keep a legacy value selectable even if it isn't in today's list. */
function withCurrent(list: string[], current?: string | null) {
  return current && !list.includes(current) ? [current, ...list] : list
}

function EmptyHint({ to, label }: { to: string; label: string }) {
  return <Link to={to} className="text-xs font-medium text-brand-600 hover:underline">{label}</Link>
}
